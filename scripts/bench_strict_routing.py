"""Same-session cost of exact top-k against query-centroid routing (DeiT-Tiny / Pet).

Usage: ``bench_strict_routing.py [strict_sr|strict|fast] [k ...]`` (default ``strict_sr 16 32 64``).
For each k, loads ``ts_surgery_topk{k}_{graph}.pt`` (exact top-k: all N^2 scores) and
``ts_surgery_topk{k}_{graph}_qc32.pt`` (routed support: N*k scores only; polarization in the strict
graph, a batched product in the fast/extended graph), and measures in one process, after one warm-up
pass each: validation accuracy, wall time of a full validation pass relative to the bf16 reference,
peak GPU memory, and unary evaluations per image (hook count). Writes
``artifacts/metadata/routing_{graph}_bench.json``.
"""

from __future__ import annotations

import json
import sys
from typing import Any, Dict, List

KS = [16, 32, 64]


def main() -> None:
    from transformer_surgery.cli.common import apply_device_from_config, apply_dtype_from_config
    from transformer_surgery.cli.surgery_config import SurgeryConfig
    from transformer_surgery.internal.pointwise import count_pointwise_per_input
    from transformer_surgery.models.adapters import get_model_adapter, load_surgery_student_checkpoint
    from transformer_surgery.surgery import _timed_evaluate

    args = sys.argv[1:]
    graph = args.pop(0) if args and args[0] in ("strict", "strict_sr", "fast") else "strict_sr"
    ks = [int(a) for a in args] or KS
    out_path = f"artifacts/metadata/routing_{graph}_bench.json"
    cfg = SurgeryConfig.load(f"configs/surgery/topk{ks[0]}_{graph}.json")
    apply_device_from_config(cfg)
    apply_dtype_from_config(cfg)
    adapter = get_model_adapter(cfg.model_key)
    _train, val = adapter.build_loaders(cfg)
    from transformer_surgery.internal.util import get_device, get_surgery_dtype

    device = get_device()
    ref = adapter.load_reference_checkpoint(adapter.reference_checkpoint_path(cfg)).to(device=device, dtype=get_surgery_dtype())
    _timed_evaluate(adapter, ref, val, cfg, device)
    ref_run = _timed_evaluate(adapter, ref, val, cfg, device)
    ref_acc, ref_time, ref_mem = ref_run.primary, ref_run.wall_time_sec, ref_run.peak_gpu_mem_bytes
    del ref
    x_count = next(iter(val))[0][:4]
    rows: List[Dict[str, Any]] = []
    for k in ks:
        for variant, name in (("topk", f"topk{k}_{graph}"), ("routed_qc32", f"topk{k}_{graph}_qc32")):
            run_cfg = SurgeryConfig.load(f"configs/surgery/{name}.json")
            model, _extra = load_surgery_student_checkpoint(f"artifacts/checkpoints/ts_surgery_{name}.pt", run_cfg)
            _timed_evaluate(adapter, model, val, run_cfg, device)
            run = _timed_evaluate(adapter, model, val, run_cfg, device)
            acc, t, mem = run.primary, run.wall_time_sec, run.peak_gpu_mem_bytes
            pw = count_pointwise_per_input(model, x_count)
            rows.append(
                {
                    "k": k,
                    "variant": variant,
                    "checkpoint": f"ts_surgery_{name}.pt",
                    "acc": float(acc),
                    "latency_vs_ref": float(t / ref_time),
                    "peak_mem_bytes": int(mem) if mem is not None else None,
                    "pointwise_per_image": pw.per_input,
                    "pointwise_by_type": pw.by_type,
                }
            )
            print(
                f"k={k:3d} {variant:12s} acc={100 * acc:6.2f} latency={t / ref_time:5.2f}x "
                f"mem={(mem or 0) / 2**20:7.0f} MB pointwise/img={pw.per_input:.4g}",
                flush=True,
            )
            del model
    out = {
        "note": "generated by scripts/bench_strict_routing.py; one process, warm-up pass before each timed pass",
        "ref_acc": float(ref_acc),
        "ref_val_time_s": float(ref_time),
        "ref_peak_mem_bytes": int(ref_mem) if ref_mem is not None else None,
        "rows": rows,
    }
    out["graph"] = graph
    with open(out_path, "w") as f:
        json.dump(out, f, indent=1)
    print(f"reference acc={100 * ref_acc:.2f} time={ref_time:.2f}s mem={(ref_mem or 0) / 2**20:.0f} MB")
    print(f"wrote {out_path}")


if __name__ == "__main__":
    main()
