"""bf16 error of the strict value mix on real DeiT-Tiny / Pet inputs (paper Supplementary, polarization and squares).

Captures the float64 inputs (probs, idx, v) of every block's mix on 16 Pet validation images, then evaluates in bf16
under CUDA autocast and reports ||y - y_fp64|| / ||y_fp64||, averaged over the 12 blocks, for
  polarization      : the polarization kernel of strict_product="polarization" (sums the squares over keys, then
                      subtracts, inside one contraction);
  norm_partial      : 1/2 [sum_k (p+v)^2 - sum_k p^2 - sum_k v^2], each partial sum rounded to bf16 (emulated);
  norm_per_term     : the default strict construction, 1/2 [sum_k (v^2 - (v-p)^2) + sum_k p^2] with the two close squares
                      subtracted per term inside the node that sums over keys;
  norm_per_term_lam : the same with the fixed scaling p -> lam p, v -> v / lam, lam^2 = ||v|| / ||p|| per block, fitted on
                      8 other images (emulated).
and the cancellation factor sum_k v_k^2 / |y| of the mix.

Usage: python scripts/mix_precision.py [k ...]   (default 16 197; uses ts_surgery_topk{k}_strict_sr.pt)
"""

from __future__ import annotations

import json
import os
import sys
import warnings

import torch

from transformer_surgery.cli.ptq_config import PTQSurgeryConfig
from transformer_surgery.internal.util import set_default_device, set_surgery_dtype
from transformer_surgery.models.adapters import get_model_adapter, load_surgery_student_checkpoint
from transformer_surgery.ops import SparseWeightedSumBySquare


def gather(v: torch.Tensor, idx: torch.Tensor) -> torch.Tensor:
    nq, d = idx.shape[2], v.shape[-1]
    return v.unsqueeze(2).expand(-1, -1, nq, -1, -1).gather(3, idx.unsqueeze(-1).expand(*idx.shape, d))


def bf(t: torch.Tensor) -> torch.Tensor:
    return t.to(torch.bfloat16).to(torch.float64)


def norm_partial(p, idx, v):
    a, b = bf(p.unsqueeze(-1).expand(*p.shape, v.shape[-1])), bf(gather(v, idx))
    return bf(0.5 * (bf(bf(bf(a + b) ** 2).sum(-2)) - bf(bf(a ** 2).sum(-2)) - bf(bf(b ** 2).sum(-2))))


def norm_per_term_scaled(p, idx, v, lam):
    a, b = bf(bf(p.unsqueeze(-1).expand(*p.shape, v.shape[-1])) * lam), bf(bf(gather(v, idx)) / lam)
    return bf(0.5 * ((bf(b ** 2) - bf(bf(b - a) ** 2)).sum(-2) + bf(a ** 2).sum(-2)))


def main() -> None:
    ks = [int(a) for a in sys.argv[1:]] or [16, 197]
    warnings.simplefilter("ignore", FutureWarning)
    dev = torch.device("cuda")
    set_default_device(dev)
    cfg = PTQSurgeryConfig()
    cfg.top_k, cfg.eps, cfg.batch_size, cfg.workers = None, None, 8, 0
    _, val = get_model_adapter("deit_tiny_pet").build_loaders(cfg)
    it = iter(val)
    x_fit = next(it)[0].to(dev, torch.float64)
    x_eval = torch.cat([next(it)[0], next(it)[0]]).to(dev, torch.float64)
    out = {"note": "generated by scripts/mix_precision.py", "rows": []}
    for k in ks:
        set_surgery_dtype(torch.float64)
        model, _ = load_surgery_student_checkpoint(f"artifacts/checkpoints/ts_surgery_topk{k}_strict_sr.pt", cfg)
        model = model.to(dev, torch.float64).eval()

        def capture(x):
            caps = []
            hs = [b.attn.sparse_mix.register_forward_pre_hook(lambda m, a: caps.append(a)) for b in model.blocks]
            with torch.no_grad():
                model(x)
            for h in hs:
                h.remove()
            return caps

        fit, ev = capture(x_fit), capture(x_eval)
        set_surgery_dtype(torch.bfloat16)
        kernels = {
            "polarization": SparseWeightedSumBySquare(strict_product="polarization").to(dev, torch.bfloat16),
            "norm_per_term": SparseWeightedSumBySquare(strict_product="norm").to(dev, torch.bfloat16),
        }
        errs = {n: [] for n in ("polarization", "norm_partial", "norm_per_term", "norm_per_term_lam")}
        ratio = []
        with torch.no_grad():
            for (pf, idf, vf), (p, idx, v) in zip(fit, ev):
                y = (p.unsqueeze(-1) * gather(v, idx)).sum(-2)
                ratio.append(((gather(v, idx) ** 2).sum(-2).abs().mean() / y.abs().mean()).item())
                for n, m in kernels.items():
                    with torch.autocast("cuda", dtype=torch.bfloat16):
                        yh = m(p.bfloat16(), idx, v.bfloat16())
                    errs[n].append(((yh.double() - y).norm() / y.norm()).item())
                errs["norm_partial"].append(((norm_partial(p, idx, v) - y).norm() / y.norm()).item())
                lam = ((gather(vf, idf) ** 2).sum(-2).mean() / (pf ** 2).sum(-1).mean()) ** 0.25
                yl = norm_per_term_scaled(p, idx, v, lam.item())
                errs["norm_per_term_lam"].append(((yl - y).norm() / y.norm()).item())
        row = {"k": k, "cancellation_factor": sum(ratio) / len(ratio)}
        row.update({n: sum(e) / len(e) for n, e in errs.items()})
        out["rows"].append(row)
        print(f"k={k:3d} sum v^2/|y|={row['cancellation_factor']:6.1f}  " + "  ".join(f"{n}={100 * row[n]:.1f}%" for n in errs))
    os.makedirs("artifacts/metadata", exist_ok=True)
    with open("artifacts/metadata/mix_precision.json", "w") as f:
        json.dump(out, f, indent=1)
    print("wrote artifacts/metadata/mix_precision.json")


if __name__ == "__main__":
    main()
